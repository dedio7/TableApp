val LocalStrings = staticCompositionLocalOf { ItalianStrings }

@Composable
fun ProvideLocalization(language: String, content: @Composable () -> Unit) {
    val strings = if (language == "EN") EnglishStrings else ItalianStrings
    CompositionLocalProvider(LocalStrings provides strings) {
        content()
    }
}
